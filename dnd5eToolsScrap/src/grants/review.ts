import type { CoverageGap } from "./coverage.ts";

/**
 * The review list as Markdown: one entry per uncovered feature, grouped by
 * owner, with the matched sentences only. The input is the coverage gaps in
 * data order, so the output is stable across runs.
 */
export function renderReview(gaps: CoverageGap[]): string {
  const byOwner = new Map<string, CoverageGap[]>();
  for (const gap of gaps) {
    const list = byOwner.get(gap.owner) ?? [];
    list.push(gap);
    byOwner.set(gap.owner, list);
  }

  const lines = [
    "# Proficiency grant review",
    "",
    `${gaps.length} entries. Each needs a decision: a grant in src/overrides/proficiency-grants.ts, or a mark in REVIEWED_GRANTS_NOTHING in the same file.`,
    "Generated by `npm --prefix dnd5eToolsScrap run review:grants`; do not edit by hand.",
    "",
  ];
  for (const [owner, ownerGaps] of byOwner) {
    lines.push(`## ${owner}`, "");
    for (const gap of ownerGaps) {
      lines.push(`- ${gap.feature} (level ${gap.level})`);
      for (const sentence of gap.sentences) lines.push(`  - ${sentence}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}
