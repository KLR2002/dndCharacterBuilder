import type { ReviewedFeature } from "../overrides/proficiency-grants.ts";
import type { GrantOverride } from "../parser/proficiency-grants.ts";
import type { ProficiencyGrantSpec } from "../types/proficiency.ts";
import type { CoverageGap } from "./coverage.ts";

/** Every decision of the review, for the file the user reads. */
export interface ReviewDecisions {
  /** Grants added, as written in the override file. */
  grants: GrantOverride[];
  /** Features marked as granting nothing. */
  marks: ReviewedFeature[];
  /** Matches that still have no decision. */
  open: CoverageGap[];
  /** The notes section of the decisions file, Markdown, from its heading on. */
  notes: string;
}

/**
 * The review as Markdown: every grant added and every mark, grouped by owner,
 * then the open matches with their matched sentences, then the notes. The
 * output is stable across runs. Generated; do not edit by hand.
 */
export function renderDecisionReview(decisions: ReviewDecisions): string {
  const lines = [
    "# Proficiency grant review",
    "",
    `${decisions.grants.length} grants added, ${decisions.marks.length} marked as granting nothing, ${decisions.open.length} still open.`,
    "Generated by `npm --prefix dnd5eToolsScrap run review:grants`; do not edit by hand. Grants come from src/overrides/proficiency-grants.ts, marks from REVIEWED_GRANTS_NOTHING in the same file.",
    "",
    "## Grants added",
    "",
    ...byOwner(decisions.grants, (g) => [`- ${g.feature} (level ${g.level}): ${g.grants.map(describeGrant).join("; ")}`]),
    "## Marked as granting nothing",
    "",
    ...byOwner(decisions.marks, (m) => [`- ${m.feature} (level ${m.level})`]),
    "## Still open",
    "",
    ...byOwner(decisions.open, (gap) => [
      `- ${gap.feature} (level ${gap.level})`,
      ...gap.sentences.map((sentence) => `  - ${sentence}`),
    ]),
    decisions.notes.trimEnd(),
    "",
  ];
  return lines.join("\n");
}

/** A grant as one line of names: `skills: Insight, Medicine`, `tools: choose 1 from ...`. */
export function describeGrant(spec: ProficiencyGrantSpec): string {
  if (spec.kind === "fixed") return `${spec.category}: ${spec.names.join(", ")}`;
  const { pool } = spec;
  if (pool.kind === "any") return `${spec.category}: choose ${spec.count} of any`;
  if (pool.kind === "names") return `${spec.category}: choose ${spec.count} from ${pool.names.join(", ")}`;
  const rule = [`${pool.base.join(" and ")} weapons`];
  if (pool.withoutProperties.length > 0) rule.push(`without ${pool.withoutProperties.join(", ")}`);
  if (pool.attackType) rule.push(`${pool.attackType} only`);
  if (pool.plus.length > 0) rule.push(`plus ${pool.plus.join(", ")}`);
  return `${spec.category}: choose ${spec.count} from ${rule.join(", ")}`;
}

/** The notes section of the decisions file: from its `## Notes for the user` heading to the end. */
export function notesSection(decisionsMarkdown: string): string {
  const match = /^## Notes for the user.*$/m.exec(decisionsMarkdown);
  if (!match) throw new Error("the decisions file has no `## Notes for the user` section");
  return decisionsMarkdown.slice(match.index).trimEnd();
}

/** Groups items by owner, in first-seen order: one heading per owner, then its lines. "None." when empty. */
function byOwner<T extends { owner: string }>(items: T[], render: (item: T) => string[]): string[] {
  if (items.length === 0) return ["None.", ""];
  const owners = [...new Set(items.map((item) => item.owner))];
  return owners.flatMap((owner) => [
    `### ${owner}`,
    "",
    ...items.filter((item) => item.owner === owner).flatMap(render),
    "",
  ]);
}
